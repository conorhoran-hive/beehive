// Builds the eligibility form from src/ into two outputs:
//   dist/webflow-embed.html — paste into a Webflow "Code Embed" element (< 50,000 chars)
//   dist/index.html         — standalone page, drop-in replacement for the current iframe page
//
// Usage: npm run build
import { build, transform } from 'esbuild';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const WEBFLOW_EMBED_LIMIT = 50_000;
const TARGET = ['chrome90', 'firefox90', 'safari14', 'edge90'];

// React production UMD builds from unpkg, with SRI hashes computed from the
// identical files in node_modules (unpkg serves the npm tarball verbatim).
const sri = (file) => 'sha384-' + createHash('sha384').update(readFileSync(file)).digest('base64');
const reactScripts = ['react', 'react-dom'].map((pkg) => {
  const file = `umd/${pkg}.production.min.js`;
  const { version } = JSON.parse(readFileSync(`node_modules/${pkg}/package.json`, 'utf8'));
  return `<script src="https://unpkg.com/${pkg}@${version}/${file}" integrity="${sri(`node_modules/${pkg}/${file}`)}" crossorigin="anonymous"></script>`;
}).join('\n');

const fonts = `<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&display=swap" rel="stylesheet">`;

const { code: css } = await transform(readFileSync('src/form.css', 'utf8'), {
  loader: 'css', minify: true, target: TARGET,
});

const buildJs = async (embed) => {
  const result = await build({
    entryPoints: ['src/form.jsx'],
    bundle: false,
    write: false,
    minify: true,
    format: 'iife',
    target: TARGET,
    jsxFactory: 'h',
    jsxFragment: 'F',
    banner: { js: 'var h=React.createElement,F=React.Fragment;' },
    define: { EMBED: String(embed) },
    legalComments: 'none',
  });
  // banner sits outside the IIFE; move it inside so nothing leaks to window
  const js = result.outputFiles[0].text.trim();
  const banner = 'var h=React.createElement,F=React.Fragment;';
  const wrapped = js.replace(banner, '').trim().replace(/^\(\(\)=>\{/, `(()=>{${banner}`);
  if (!wrapped.startsWith(`(()=>{${banner}`)) throw new Error('unexpected esbuild output shape');
  return wrapped;
};

const body = (js) => `<div id="beehive-form"><div id="root"></div></div>
${reactScripts}
<script>${js}</script>`;

mkdirSync('dist', { recursive: true });

// Inline embed: no <html>/<head>; no ContentSquare tag (the Webflow page's own
// CS tag captures the form once it's in the page DOM).
const embed = `<!-- Beehive eligibility form — generated by build.mjs from src/. Do not edit by hand. -->
${fonts}
<style>${css}</style>
${body(await buildJs(true))}
`;
writeFileSync('dist/webflow-embed.html', embed);

// Standalone (iframe) page: same head as today, incl. the ContentSquare tag.
const standalone = `<!DOCTYPE html><html lang="en" style="--accent: #E00800;"><head>
<!-- GTM intentionally NOT loaded inside the iframe — events are relayed to the parent page's dataLayer via postMessage. -->
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<title>Beehive — Business Eligibility Check</title>
<script src="https://t.contentsquare.net/uxa/24e5fc3c98aa4.js" defer></script>
${fonts}
<style>html,body{overflow:hidden}${css}</style>
</head>
<body class="theme-light">
${body(await buildJs(false))}
</body></html>
`;
writeFileSync('dist/index.html', standalone);

const report = (name, s) => console.log(`${name.padEnd(26)} ${String(s.length).padStart(7)} chars`);
report('legacy/original.html', readFileSync('legacy/original.html', 'utf8'));
report('dist/index.html', standalone);
report('dist/webflow-embed.html', embed);
if (embed.length > WEBFLOW_EMBED_LIMIT) {
  console.error(`webflow-embed.html exceeds Webflow's ${WEBFLOW_EMBED_LIMIT} character limit`);
  process.exit(1);
}
